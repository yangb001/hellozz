router = APIRouter(prefix="/api/v1")


@router.get("/health")
async def health_check():
    """Health check endpoint.

    Returns:
        dict: Status information indicating the service is healthy.
    """
    return {"status": "ok", "service": "agent-framework"}


@router.get("/")
async def root():
    """Root endpoint.

    Returns:
        dict: Welcome message.
    """
    return {"message": "Welcome to Agent Framework API"}


@router.post("/sessions", response_model=CreateSessionResponse)
async def create_session(
    request: CreateSessionRequest,
    session_manager: Optional[SessionManager] = Depends(get_session_manager)
):
    """Create a new session.

    Args:
        request: CreateSessionRequest containing session parameters.
        session_manager: SessionManager dependency.

    Returns:
        CreateSessionResponse with session details.

    Raises:
        HTTPException: If session creation fails.
    """
    if session_manager is None:
        raise HTTPException(
            status_code=500,
            detail=ErrorResponse(error="Service unavailable", detail="SessionManager not initialized").dict()
        )

    try:
        ctx = await session_manager.create_session(
            user_id=request.user_id,
            session_type=request.session_type,
            participants=request.participants
        )
        return _session_to_response(ctx)
    except Exception as e:
        raise HTTPException(
            status_code=500,
            detail=ErrorResponse(error="Session creation failed", detail=str(e)).dict()
        )


@router.get("/sessions/{session_id}", response_model=SessionInfoResponse)
async def get_session(
    session_id: str,
    session_manager: Optional[SessionManager] = Depends(get_session_manager)
):
    """Get session information.

    Args:
        session_id: ID of the session to retrieve.
        session_manager: SessionManager dependency.

    Returns:
        SessionInfoResponse with session details.

    Raises:
        HTTPException: If session is not found or retrieval fails.
    """
    if session_manager is None:
        raise HTTPException(
            status_code=500,
            detail=ErrorResponse(error="Service unavailable", detail="SessionManager not initialized").dict()
        )

    try:
        ctx = await session_manager.get_session(session_id)
        if ctx is None:
            raise HTTPException(
                status_code=404,
                detail=ErrorResponse(
                    error="Session not found",
                    detail=f"Session with ID '{session_id}' does not exist"
                ).dict()
            )
        return _session_to_info(ctx)
    except HTTPException:
        raise
    except Exception as e:
        raise HTTPException(
            status_code=500,
            detail=ErrorResponse(error="Failed to retrieve session", detail=str(e)).dict()
        )


@router.post("/sessions/{session_id}/messages")
async def send_message(
    session_id: str,
    request: SendMessageRequest,
    session_manager: Optional[SessionManager] = Depends(get_session_manager)
):
    """Send a message to a session and receive streaming SSE response.

    Args:
        session_id: ID of the session to send message to.
        request: SendMessageRequest containing message content.
        session_manager: SessionManager dependency.

    Returns:
        StreamingResponse with text/event-stream content type.
    """
    if session_manager is None:
        raise HTTPException(
            status_code=500,
            detail="SessionManager not initialized"
        )

    async def event_generator():
        try:
            user_msg = {
                "role": "user",
                "content": request.content,
                "sender_id": request.sender_id
            }

            async for event in session_manager.process_message_stream(session_id, user_msg):
                event_data = {
                    "type": event.type,
                    "content": event.content,
                    "metadata": event.metadata,
                    "timestamp": event.timestamp.isoformat() if event.timestamp else None
                }
                yield f"data: {json.dumps(event_data)}\n\n"

            yield f"data: {{\"type\": \"done\", \"content\": \"\"}}\n\n"

        except ValueError as e:
            error_data = {"type": "error", "content": str(e)}
            yield f"data: {json.dumps(error_data)}\n\n"
        except Exception as e:
            logger.error(f"Error in stream processing session {session_id}: {e}", exc_info=True)
            error_data = {"type": "error", "content": f"Processing error: {str(e)}"}
            yield f"data: {json.dumps(error_data)}\n\n"

    return StreamingResponse(
        event_generator(),
        media_type="text/event-stream",
        headers={
            "Cache-Control": "no-cache",
            "Connection": "keep-alive",
            "X-Accel-Buffering": "no"
        }
    )


