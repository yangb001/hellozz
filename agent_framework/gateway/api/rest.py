@router.get("/sessions/{session_id}/messages", response_model=MessageHistoryResponse)
async def get_message_history(
    session_id: str,
    limit: Optional[int] = Query(None, ge=1, le=100, description="Maximum number of messages to return"),
    session_manager: Optional[SessionManager] = Depends(get_session_manager)
):
    """Get message history for a session.

    Args:
        session_id: ID of the session to get messages from.
        limit: Optional maximum number of messages to return (1-100).
        session_manager: SessionManager dependency.

    Returns:
        MessageHistoryResponse with message list.

    Raises:
        HTTPException: If session is not found or retrieval fails.
    """
    if session_manager is None:
        raise HTTPException(
            status_code=500,
            detail=ErrorResponse(error="Service unavailable", detail="SessionManager not initialized").dict()
        )

    try:
        ctx = await session_manager.get_session(session_id)
        if ctx is None:
            raise HTTPException(
                status_code=404,
                detail=ErrorResponse(
                    error="Session not found",
                    detail=f"Session with ID '{session_id}' does not exist"
                ).dict()
            )

        # Get messages, optionally limited
        messages = ctx.messages
        if limit is not None:
            messages = messages[-limit:]  # Return most recent messages

        # Convert messages to dict format
        message_dicts = [_message_to_dict(msg) for msg in messages]

        return MessageHistoryResponse(
            session_id=session_id,
            messages=message_dicts,
            total_count=len(ctx.messages)
        )
    except HTTPException:
        raise
    except Exception as e:
        raise HTTPException(
            status_code=500,
            detail=ErrorResponse(error="Failed to retrieve messages", detail=str(e)).dict()
        )