"""REST API router.

This module defines the REST API endpoints for the agent framework,
including session management and message handling.

参考：详细设计.md 第8节
"""
import logging
import json
from datetime import datetime, timezone
from typing import List, Optional, Dict, Any
from asyncio import Queue

from fastapi import APIRouter, HTTPException, Depends, Query
from fastapi.responses import StreamingResponse
from pydantic import BaseModel, Field

from ..dependencies import get_session_manager
from ...core.session_manager import SessionManager
from ...interfaces.session import SessionContext, Message

logger = logging.getLogger("agent_framework.gateway.rest")


# ============================================================================
# Pydantic Models for Request/Response
# ============================================================================

class CreateSessionRequest(BaseModel):
    """Request model for creating a new session.

    Attributes:
        user_id: ID of the user creating the session.
        session_type: Type of session ('private' or 'group').
        participants: Optional list of additional participant IDs.
    """
    user_id: str
    session_type: str = "private"
    participants: Optional[List[str]] = None


class CreateSessionResponse(BaseModel):
    """Response model for session creation.

    Attributes:
        session_id: Unique identifier for the created session.
        session_type: Type of session.
        participants: List of participant IDs.
        status: Session status.
        created_at: Session creation timestamp.
    """
    session_id: str
    session_type: str
    participants: List[str]
    status: str
    created_at: datetime


class SessionInfoResponse(BaseModel):
    """Response model for session information.

    Attributes:
        session_id: Unique identifier for the session.
        session_type: Type of session.
        participants: List of participant IDs.
        status: Session status.
        message_count: Number of messages in the session.
        created_at: Session creation timestamp.
        last_active: Last activity timestamp.
    """
    session_id: str
    session_type: str
    participants: List[str]
    status: str
    message_count: int
    created_at: datetime
    last_active: datetime


class SendMessageRequest(BaseModel):
    """Request model for sending a message.

    Attributes:
        content: Message content.
        sender_id: Optional ID of the message sender.
    """
    content: str
    sender_id: Optional[str] = None


class SendMessageResponse(BaseModel):
    """Response model for message sending.

    Attributes:
        session_id: ID of the session.
        events: List of events generated by the agent.
        message_count: Total number of messages after sending.
    """
    session_id: str
    events: List[Dict[str, Any]]
    message_count: int


class MessageHistoryResponse(BaseModel):
    """Response model for message history.

    Attributes:
        session_id: ID of the session.
        messages: List of messages in the session.
        total_count: Total number of messages.
    """
    session_id: str
    messages: List[Dict[str, Any]]
    total_count: int


class ErrorResponse(BaseModel):
    """Error response model.

    Attributes:
        error: Error type or summary.
        detail: Detailed error description.
    """
    error: str
    detail: Optional[str] = None


# ============================================================================
# Helper Functions
# ============================================================================

def _message_to_dict(message: Message) -> Dict[str, Any]:
    """Convert a Message object to a dictionary.

    Args:
        message: Message object to convert.

    Returns:
        Dictionary representation of the message.
    """
    return {
        "role": message.role,
        "content": message.content,
        "sender_id": message.sender_id,
        "timestamp": message.timestamp.isoformat() if message.timestamp else None
    }


def _session_to_response(ctx: SessionContext) -> CreateSessionResponse:
    """Convert a SessionContext to a CreateSessionResponse.

    Args:
        ctx: SessionContext to convert.

    Returns:
        CreateSessionResponse instance.
    """
    return CreateSessionResponse(
        session_id=ctx.session_id,
        session_type=ctx.session_type,
        participants=ctx.participants,
        status=ctx.status,
        created_at=ctx.created_at
    )


def _session_to_info(ctx: SessionContext) -> SessionInfoResponse:
    """Convert a SessionContext to a SessionInfoResponse.

    Args:
        ctx: SessionContext to convert.

    Returns:
        SessionInfoResponse instance.
    """
    return SessionInfoResponse(
        session_id=ctx.session_id,
        session_type=ctx.session_type,
        participants=ctx.participants,
        status=ctx.status,
        message_count=len(ctx.messages),
        created_at=ctx.created_at,
        last_active=ctx.last_active
    )


